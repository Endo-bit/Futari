/* The day's prompt and couple question live in ./prompts, one module per
   language, and are folded on here under the names the screens already use. */
for (const lang of LANGS) {
  const p = PROMPTS[lang];
  if (!p) continue;
  T[lang].prompts = p.pair;
  T[lang].promptsSolo = p.solo;
  T[lang].coupleQuestions = p.quiz;
}

/* Guided-tour copy and the demo partner's page, from ./tutorialText. */
for (const lang of LANGS) {
  Object.assign(T[lang], TUTORIAL_T[lang] || TUTORIAL_T.en, INVITE_T[lang] || INVITE_T.en);
}

/** RN has no `navigator.language` — use the device locale from expo-localization. */
export function detectLang() {
  try {
    const { getLocales } = require("expo-localization");
    const locales = getLocales();
    const code = (locales?.[0]?.languageCode || "en").toLowerCase();
    return LANGS.includes(code) ? code : "en";
  } catch {
    return "en";
  }
}
